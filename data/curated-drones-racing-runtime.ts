import type { CuratedDroneRecord } from "@/lib/catalog-schema";
import type { AircraftProfile, ControlProtocol, VideoSystem } from "@/lib/schema";

function raceProfile(
  system: VideoSystem,
  unit: string,
  protocol: ControlProtocol,
  cells: number,
  capacity: [number, number, number, number],
  connector: string,
  dryWeightG?: number,
  gpsIncluded = false,
): AircraftProfile {
  return {
    sizeClass: "RACE_5",
    flightRoles: ["competitive-racing", "open-5in-racing"],
    video: { system, unit },
    control: {
      protocol,
      ...(protocol === "elrs_2.4" ? { band: "2.4GHz" as const } : {}),
    },
    battery: {
      cellsAllowed: [cells],
      chemistriesAllowed: ["LiPo"],
      capacityMah: {
        min: capacity[0],
        idealMin: capacity[1],
        idealMax: capacity[2],
        max: capacity[3],
      },
      connector,
    },
    prop: { diameterIn: 5 },
    recovery: { gpsIncluded, selfPoweredBuzzerIncluded: false },
    ...(dryWeightG !== undefined ? { dryWeightG } : {}),
  };
}

